  async function _seedOne({ pin, audioFile }) {
    const existing = PinStorage.getAll().find(p => p.id === pin.id);

    if (existing) {
      const diff = {};
      const fields = ['name', 'description', 'type', 'history', 'poem', 'radius'];
      for (const f of fields) {
        if (pin[f] !== undefined && existing[f] !== pin[f]) diff[f] = pin[f];
      }
      if (Object.keys(diff).length) PinStorage.update(pin.id, diff);
    } else {
      PinStorage.add({ ...pin, createdAt: Date.now() });
    }

    if (!audioFile) return;
    const alreadyHasAudio = await VoiceMapDB.hasAudio(pin.id);
    if (alreadyHasAudio) return;
    try {
      const res = await fetch(audioFile);
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const blob = await res.blob();
      await VoiceMapDB.saveAudio(pin.id, blob);
      console.info(`[Seed] "${pin.name}" พร้อมใช้งาน (radius ${pin.radius}m)`);
    } catch (err) {
      console.warn(`[Seed] โหลดเสียงไม่ได้: ${err.message}`);
    }
  }

  return { run };
